#!/usr/bin/env node
// Writes assets/fixture-machine.asset.json: a deterministic SYNTHETIC v2 machine used to develop and test the
// renderer, loaders, paths, and multi-site L2 before real structure-derived v2 assets exist. It is not a biological model.
// Shape: a two-part "enzyme" (core + accessory) wrapped around a straight B-DNA-like channel along +z.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ASSET_FORMAT, ASSET_VERSION, QUANT_STEP, encodeArray, encodePositions, validateAsset } from '../js/assets/format.js';
import { mulberry32 } from '../js/sim/util.js';
import { helixFrame, partnerFrame } from '../js/science/math.js';
import { HELIX_B } from '../js/science/templates.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rng = mulberry32(20261117);
const I3 = [1, 0, 0, 0, 1, 0, 0, 0, 1];

// Low-polygon ellipsoid mesh (UV sphere), centre c, semi-axes r.
function ellipsoid(c, r, nLat = 14, nLon = 20) {
  const pos = [], idx = [];
  for (let i = 0; i <= nLat; i++) for (let j = 0; j < nLon; j++) {
    const th = Math.PI * i / nLat, ph = 2 * Math.PI * j / nLon;
    pos.push(c[0] + r[0] * Math.sin(th) * Math.cos(ph), c[1] + r[1] * Math.sin(th) * Math.sin(ph), c[2] + r[2] * Math.cos(th));
  }
  for (let i = 0; i < nLat; i++) for (let j = 0; j < nLon; j++) {
    const a = i * nLon + j, b = i * nLon + (j + 1) % nLon, d = a + nLon, e = b + nLon;
    idx.push(a, d, b, b, d, e);
  }
  return { pos, idx };
}
// Beads scattered inside an ellipsoid but outside a cylindrical channel of radius 11 A around the z axis.
function beads(c, r, n) {
  const out = [];
  while (out.length < n * 3) {
    const u = [rng() * 2 - 1, rng() * 2 - 1, rng() * 2 - 1];
    if (u[0] * u[0] + u[1] * u[1] + u[2] * u[2] > 1) continue;
    const x = c[0] + u[0] * r[0], y = c[1] + u[1] * r[1], z = c[2] + u[2] * r[2];
    if (Math.hypot(x, y) < 11) continue;
    out.push(x, y, z);
  }
  return out;
}

const core = { c: [18, 0, 0], r: [52, 46, 60] }, acc = { c: [-30, 22, -34], r: [26, 22, 30] };
const m0 = ellipsoid(core.c, core.r), m1 = ellipsoid(acc.c, acc.r);
const b0 = beads(core.c, core.r, 520), b1 = beads(acc.c, acc.r, 110);
const lod1Pos = [...b0, ...b1];
const lod1Chain = new Uint8Array(630); lod1Chain.fill(1, 520);
const lod1Kind = new Uint8Array(630);

// A short zig-zag atom chain near the origin as the "active site".
const elements = [6, 7, 8, 16, 6, 6, 8, 7, 6, 12], a2 = [], el = [], bonds = [];
for (let i = 0; i < 60; i++) {
  a2.push(12 + Math.cos(i * 1.9) * 3 + (i % 5), -4 + Math.sin(i * 1.9) * 3, -8 + i * 0.5);
  el.push(elements[i % elements.length]);
  if (i) bonds.push(i - 1, i);
}

// Slot tracks: straight ideal B-DNA through the channel. Register 0 sits at the origin.
const registers = Array.from({ length: 31 }, (_, i) => i - 15);
const tFrames = registers.map(k => { const f = helixFrame(k, HELIX_B.rise, HELIX_B.twistDeg); return { o: f.o, R: Array.from(f.R) }; });
const ntFrames = tFrames.map(f => { const g = partnerFrame(f); return { o: g.o, R: Array.from(g.R) }; });
const seq = 'ACGTTGCAAGCTTCGATCGGATCCATGCAAT'.slice(0, registers.length);
const track = frames => ({ kind: 'dna', registers, frames, synthetic: registers.map(() => 1), bases: seq });

// Synthetic exit path from activeSite [12, -4, 0] to rnaExit [-34, 30, -40] (16 points).
const pathCount = 16, channelPts = [];
for (let i = 0; i < pathCount; i++) {
  const u = i / (pathCount - 1);
  const x = 12 + (-34 - 12) * u;
  const y = -4 + (30 - (-4)) * u + 4 * Math.sin(Math.PI * u);
  const z = 0 + (-40 - 0) * u;
  channelPts.push(x, y, z);
}

const asset = {
  format: ASSET_FORMAT, version: ASSET_VERSION, id: 'fixture-machine', name: 'Synthetic fixture machine (not a biological model)',
  kind: 'machine', units: 'angstrom', quantStep: QUANT_STEP,
  source: { type: 'synthetic', notes: ['Generated by tools/make-fixture-asset.mjs with a fixed seed (asset format v2).'] },
  bounds: { center: [8, 4, -4], radius: 78, size: [126, 96, 124] },
  parts: [
    { id: 'core', name: 'Core (synthetic)', role: 'body' },
    { id: 'accessory', name: 'Accessory factor (synthetic)', role: 'release' },
  ],
  chains: [
    { id: 'A', part: 'core', class: 'protein', name: 'Core chain', residues: 520 },
    { id: 'B', part: 'accessory', class: 'protein', name: 'Accessory chain', residues: 110 },
  ],
  lod0: { parts: [m0, m1].map((m, i) => ({ part: i ? 'accessory' : 'core', positions: encodePositions(m.pos), indices: encodeArray(Uint16Array.from(m.idx)), indexType: 'u16', vertexCount: m.pos.length / 3, triangleCount: m.idx.length / 3 })) },
  lod1: { count: 630, positions: encodePositions(lod1Pos), chain: encodeArray(lod1Chain), kind: encodeArray(lod1Kind) },
  lod2: {
    count: 60,
    positions: encodePositions(a2),
    element: encodeArray(Uint8Array.from(el)),
    chain: encodeArray(new Uint8Array(60)),
    bonds: encodeArray(Uint16Array.from(bonds)),
    bondCount: bonds.length / 2,
    sites: [
      { anchor: 'activeSite', radius: 12 },
      { anchor: 'rnaExit', radius: 8 },
    ],
  },
  anchors: {
    center: { o: [8, 4, -4], R: I3 }, activeSite: { o: [12, -4, 0], R: I3 },
    dnaEntry: { o: [0, 0, 15 * HELIX_B.rise], R: I3 }, dnaExit: { o: [0, 0, -15 * HELIX_B.rise], R: I3 }, rnaExit: { o: [-34, 30, -40], R: I3 },
  },
  tracks: { template: track(tFrames), nontemplate: track(ntFrames) },
  paths: {
    channel: { points: encodePositions(channelPts), count: pathCount, synthetic: 1 },
  },
};
const problems = validateAsset(asset);
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
const out = path.join(root, 'assets', 'fixture-machine.asset.json');
fs.writeFileSync(out, JSON.stringify(asset));
// Preserve existing manifest entries (only ensure fixture-machine is listed).
const manifestPath = path.join(root, 'assets', 'manifest.json');
const manifest = fs.existsSync(manifestPath)
  ? JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
  : { version: 1, assets: [] };
if (!manifest.assets.some(e => e.id === 'fixture-machine')) {
  manifest.assets.unshift({ id: 'fixture-machine', file: 'fixture-machine.asset.json', synthetic: true });
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
}
console.log(`wrote ${path.relative(root, out)} (${(fs.statSync(out).size / 1024).toFixed(1)} KB)`);
